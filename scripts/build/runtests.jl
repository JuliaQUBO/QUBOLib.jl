function test_minlplib_pip_parser_and_build()
    @testset "▶ MINLPLib PIP parser & QUBO collection build" begin
        @test length(MINLPLIB_QUBO_INSTANCES) == 29
        @test length(MINLPLIB_QPLIB_OVERLAP) == 18
        @test count(e -> e.proven_optimal, MINLPLIB_QUBO_INSTANCES) == 18
        @test isempty(intersect(
            Set(e.name for e in MINLPLIB_QUBO_INSTANCES),
            Set(e.minlplib_name for e in MINLPLIB_QPLIB_OVERLAP),
        ))

        # 1. Direct BQP with tenths coefficients + floating-point export noise (chimera style)
        pip_chimera = """
        \\* Source Model Name: chimera_fixture *\\

        Maximize
          obj: +0.9 b1 +0.9 b2 -1.7999999999999998 b1 b2

        Subject To

        Bounds
         0 <= b1 <= 1
         0 <= b2 <= 1

        Binary
          b1
          b2
        End
        """
        m_chimera = QUBOTools.read_model(IOBuffer(pip_chimera), Format(:minlplib_pip))
        @test QUBOTools.dimension(m_chimera) == 2
        @test String(QUBOTools.sense(m_chimera)) == "max"
        @test String(QUBOTools.domain(m_chimera)) == "bool"
        @test QUBOTools.scale(m_chimera) ≈ 0.1
        @test QUBOTools.value(m_chimera, [1, 0]) ≈ 0.9
        @test QUBOTools.value(m_chimera, [1, 1]) ≈ 0.0
        cf_chimera = _coercive_field_summary_dict(m_chimera)
        @test cf_chimera["is_gauge_invariant"] == true
        @test cf_chimera["zero_field_fraction"] ≈ 1.0

        # 2. Epigraph MBQCP maximization (sporttournament style: -Q(b) + objvar <= C)
        pip_sport = """
        Maximize
          obj: 0 b1 + 0 b2 + objvar

        Subject To
          e1: -2 b1 -2 b2 + objvar + 4 b1 b2 <= 10

        Bounds
         objvar Free

        Binary
          b1
          b2
        End
        """
        m_sport = QUBOTools.read_model(IOBuffer(pip_sport), Format(:minlplib_pip))
        @test QUBOTools.dimension(m_sport) == 2
        @test String(QUBOTools.sense(m_sport)) == "max"
        @test QUBOTools.offset(m_sport) ≈ 10.0
        @test QUBOTools.value(m_sport, [1, 0]) ≈ 12.0
        @test QUBOTools.value(m_sport, [1, 1]) ≈ 10.0
        cf_sport = _coercive_field_summary_dict(m_sport)
        @test cf_sport["is_gauge_invariant"] == true

        # 3. Epigraph MBQCP minimization (autocorr_bern style: Q(b) - objvar <= 0)
        pip_autocorr = """
        Minimize
          obj: 0 b1 + 0 b2 + objvar

        Subject To
          e1: 2 b1 + 2 b2 - objvar - 4 b1 b2 <= 0

        Bounds
         objvar Free

        Binary
          b1
          b2
        End
        """
        m_autocorr = QUBOTools.read_model(IOBuffer(pip_autocorr), Format(:minlplib_pip))
        @test QUBOTools.dimension(m_autocorr) == 2
        @test String(QUBOTools.sense(m_autocorr)) == "min"
        @test QUBOTools.offset(m_autocorr) ≈ 0.0
        @test QUBOTools.value(m_autocorr, [1, 0]) ≈ 2.0
        @test QUBOTools.value(m_autocorr, [0, 0]) ≈ 0.0
        cf_autocorr = _coercive_field_summary_dict(m_autocorr)
        @test cf_autocorr["is_gauge_invariant"] == true

        # 4. Reject malformed epigraph objectives, wrong objvar sign, and non-contiguous/invalid binary sections
        @test_throws QUBOTools.SyntaxError QUBOTools.read_model(
            IOBuffer(replace(pip_sport, "0 b1 + 0 b2 + objvar" => "1 b1 + objvar")),
            Format(:minlplib_pip),
        )
        @test_throws QUBOTools.SyntaxError QUBOTools.read_model(
            IOBuffer(replace(pip_sport, "+ objvar +" => "- objvar +")),
            Format(:minlplib_pip),
        )
        @test_throws QUBOTools.SyntaxError QUBOTools.read_model(
            IOBuffer(replace(pip_sport, "Binary\n  b1\n  b2" => "Binary\n  b1\n  x2")),
            Format(:minlplib_pip),
        )
        @test_throws QUBOTools.SyntaxError QUBOTools.read_model(
            IOBuffer(replace(pip_sport, "Binary\n  b1\n  b2" => "Binary\n  b1\n  b3")),
            Format(:minlplib_pip),
        )
        @test_throws QUBOTools.SyntaxError QUBOTools.read_model(
            IOBuffer(replace(pip_chimera, "+0.9 b2" => "+0.9 b3")),
            Format(:minlplib_pip),
        )

        fixture_instances = [
            (
                name = "sporttournament06",
                family = "sporttournament",
                formulation = "mbqcp_epigraph",
                dimension = 2,
                sense = :max,
                primal_bound = 12.0,
                dual_bound = 12.0,
                gap = 0.0,
                proven_optimal = true,
                best_point = "p1",
                points = ["p1"],
            ),
        ]

        mktempdir() do root
            write(joinpath(root, "sporttournament06.pip"), pip_sport)
            write(
                joinpath(root, "sporttournament06.p1.sol"),
                "objvar 12\nb1 1\nb2 0\n",
            )

            mktempdir() do path
                QUBOLib.access(; path, clear = true) do index
                    build_minlplib!(
                        index;
                        root      = root,
                        instances = fixture_instances,
                    )
                    @test QUBOLib.collection_size(index, "minlplib") == 1

                    inst_df = QUBOLib.DBInterface.execute(
                        QUBOLib.database(index),
                        "SELECT instance, name, problem_class, formulation, metadata FROM Instances WHERE collection = 'minlplib';",
                    ) |> QUBOLib.DataFrame
                    @test size(inst_df, 1) == 1
                    @test inst_df[1, :name] == "sporttournament06.pip"
                    @test inst_df[1, :problem_class] == "Max-Cut (Sport Tournament)"
                    @test inst_df[1, :formulation] == "mbqcp_epigraph"

                    best_rec = QUBOLib.best_solution_record(index, Int(inst_df[1, :instance]))
                    @test !isnothing(best_rec)
                    @test best_rec[:bitstring] == "10"
                    @test best_rec[:qubo_value] ≈ 12.0
                    @test best_rec[:source_value] ≈ 12.0
                    @test Bool(best_rec[:proven_optimal])
                    @test best_rec[:validation_status] == "validated"
                end
            end
        end
    end

    return nothing
end

function test_mqlib_parsers_and_build()
    @testset "▶ MQLib parsers & standard/tier2 collection build" begin
        @test length(MQLIB_HEURISTICS) == 38
        @test length(MQLIB_PALUBECKIS_DEFERRED) == 0
        @test length(MQLIB_QPLIB_OVERLAP) == 2
        @test MQLIB_QPLIB_OVERLAP["be250.8"]["qplib_source_name"] == "QPLIB_5909"
        @test MQLIB_QPLIB_OVERLAP["be500.2"]["qplib_source_name"] == "QPLIB_5922"

        # 1. Max-Cut edge list: 2 vertices, edge (1, 2) weight 3.0 => 3*(x1 + x2 - 2*x1*x2)
        mc_text = """
        # Comment line
        2 1
        1 2 3.0
        """
        m_mc = QUBOTools.read_model(IOBuffer(mc_text), Format(:mqlib_maxcut))
        @test QUBOTools.dimension(m_mc) == 2
        @test String(QUBOTools.sense(m_mc)) == "max"
        @test String(QUBOTools.domain(m_mc)) == "bool"
        @test Dict(QUBOTools.linear_terms(m_mc)) == Dict(1 => 3.0, 2 => 3.0)
        @test Dict(QUBOTools.quadratic_terms(m_mc)) == Dict((1, 2) => -6.0)
        @test QUBOTools.value(m_mc, [1, 0]) ≈ 3.0
        @test QUBOTools.value(m_mc, [1, 1]) ≈ 0.0

        # 2. QUBO converted to Max-Cut with master node (n_mc = n_qubo + 1 = 3):
        #    edge (1, 2) w = -2.0 => -2*(x1 + x2 - 2*x1*x2) = -2*x1 - 2*x2 + 4*x1*x2
        #    edge (1, 3) w = 5.0  => +5*x1 (master node 3 at x3 = 0)
        #    edge (2, 3) w = 1.0  => +1*x2
        #    Net QUBO: 3*x1 - 1*x2 + 4*x1*x2
        qmc_text = """
        # Converted to a MAX-CUT problem
        3 3
        1 2 -2.0
        1 3 5.0
        2 3 1.0
        """
        m_qmc = QUBOTools.read_model(IOBuffer(qmc_text), Format(:mqlib_qubo_maxcut))
        @test QUBOTools.dimension(m_qmc) == 2
        @test Dict(QUBOTools.linear_terms(m_qmc)) == Dict(1 => 3.0, 2 => -1.0)
        @test Dict(QUBOTools.quadratic_terms(m_qmc)) == Dict((1, 2) => 4.0)
        @test QUBOTools.value(m_qmc, [1, 1]) ≈ 6.0
        @test QUBOTools.value(m_qmc, [1, 0]) ≈ 3.0

        # 3. Direct MQLib QUBO format (diagonal = linear, off-diagonal doubled per PopulateFromAssignments)
        qd_text = """
        2 3
        1 1 3.0
        2 2 -1.0
        1 2 2.0
        """
        m_qd = QUBOTools.read_model(IOBuffer(qd_text), Format(:mqlib_qubo))
        @test QUBOTools.dimension(m_qd) == 2
        @test Dict(QUBOTools.linear_terms(m_qd)) == Dict(1 => 3.0, 2 => -1.0)
        @test Dict(QUBOTools.quadratic_terms(m_qd)) == Dict((1, 2) => 4.0)
        @test QUBOTools.value(m_qd, [1, 1]) ≈ 6.0

        mktempdir() do root
            write(
                joinpath(root, "standard.csv"),
                """
                graphname,source,problem,optimal,optimalSource
                G55.zip,G-set,MAX-CUT,,
                be250.8.zip,Beasley,QUBO,6.0,BiqMac
                p3000_2.zip,Palubeckis,QUBO,,
                """,
            )
            write(
                joinpath(root, "catalog_tier2.csv"),
                """
                graphname,source,problem,n,m,comment
                imgseg_100080.zip,ImageSeg,MAX-CUT,2,1,ImageSegmentation100080
                """,
            )
            write(
                joinpath(root, "metrics_standard.csv"),
                """
                graphname,deg_mean,percent_pos
                G55.zip,1.0,1.0
                be250.8.zip,1.5,0.666
                imgseg_100080.zip,1.0,1.0
                """,
            )
            write(
                joinpath(root, "results_standard.csv"),
                """
                graphname,heuristic,best_objective,seed,limit,timestamp
                G55.zip,BURER2002,4.0,144,1.0,2016-07-10 00:00:00
                be250.8.zip,PALUBECKIS2004bMST2,6.0,144,1.0,2016-07-10 00:00:00
                imgseg_100080.zip,DESOUSA2013,3.0,144,1.0,2016-07-10 00:00:00
                """,
            )
            write(joinpath(root, "G55.txt"), mc_text)
            write(
                joinpath(root, "G55.sol"),
                "# heuristic=BURER2002 seed=144 objective=3.0 runtime=0.1 paper_best=4.0\n10\n",
            )
            write(joinpath(root, "be250.8.txt"), qmc_text)
            write(
                joinpath(root, "be250.8.sol"),
                "# heuristic=PALUBECKIS2004bMST2 seed=144 objective=6.0 runtime=0.1 paper_best=6.0\n11\n",
            )
            write(joinpath(root, "imgseg_100080.txt"), mc_text)

            mktempdir() do path
                QUBOLib.access(; path, clear = true) do index
                    build_mqlib!(index; root = root)

    SUBMODULAR_CALL_COUNT[] += 1
    THROW_SUBMODULAR_INTERNAL_ERROR[] && (1 + "internal_submodular_kw_bug")
    push!(ws.submodular_allow_weak, allow_weak)
    return (fixings = Pair{Int,Int}[],)

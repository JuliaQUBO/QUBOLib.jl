                    @test QUBOLib.has_solver(index, "MQLib::BURER2002")
                    @test QUBOLib.has_solver(index, "MQLib::PALUBECKIS2004bMST2")
                    @test QUBOLib.has_solver(index, "MQLib::DESOUSA2013")


function _deploy_hashes(build_path::AbstractString)
    return (
        tree = strip(read(joinpath(build_path, "git-tree.hash"), String)),
        tar = strip(read(joinpath(build_path, "tar-ball.hash"), String)),
    )
end

function test_deploy_qubolib_outputs()
    @testset "▶ Deploy outputs" begin
        if Sys.islinux()
            mktempdir() do path
                write(
                    joinpath(path, "Artifacts.toml"),
                    """
                    [qubolib]
                    git-tree-sha1 = "abc"
                    lazy = true

                        [[qubolib.download]]
                        url = "https://github.com/JuliaQUBO/QUBOLib.jl/releases/download/v0.1.0-data+1/qubolib.tar.gz"
                        sha256 = "def"
                    """,
                )

                packaged_index = QUBOLib.access(; path, clear = true) do index
                    deploy_qubolib!(index)
                    return index
                end

                build_path = QUBOLib.build_path(path)

                @test isfile(joinpath(build_path, "git-tree.hash"))
                @test isfile(joinpath(build_path, "tar-ball.hash"))
                @test isfile(joinpath(build_path, "qubolib.tar.gz"))
                @test isfile(joinpath(build_path, "Artifacts.toml"))
                @test isfile(joinpath(build_path, "NOTES.md"))

                hashes = _deploy_hashes(build_path)
                @test hashes.tree ==
                      bytes2hex(Pkg.GitTools.tree_hash(QUBOLib.library_path(path)))
                @test hashes.tar ==
                      bytes2hex(open(SHA.sha256, joinpath(build_path, "qubolib.tar.gz")))

                # Repackage the same closed files. Reopening HDF5 in write mode
                # can change file metadata, which is a different input artifact.
                deploy_qubolib!(packaged_index)

                @test _deploy_hashes(build_path) == hashes
            end
        end
    end

    return nothing
end

function _write_qoblib_fixture_group(root::AbstractString, group, filenames)
    group_path = mkpath(joinpath(root, group.path))

    write(joinpath(group_path, "README.md"), "# Fixture\n")
    write(
        joinpath(group_path, "metrics.csv"),
        join(
            vcat(
                ["file,num_variables,density,min_coeff,max_coeff"],
                ["$(basename(filename)),3,$(4 / 6),-4.0,3.0" for filename in filenames],
            ),
            "\n",
        ) * "\n",
    )

    for filename in filenames
        model_path = joinpath(group_path, filename)

        mkpath(dirname(model_path))
        write(model_path, _qoblib_fixture())
    end

    return nothing
end


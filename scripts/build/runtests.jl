function probe_variables!(ws::Workspace; order::Symbol = :index, kwargs...)
    push!(ws.probed_orders, order)
    if !(1 in ws._state.fixes)
        push!(ws._state.fixes, 1)
        ws._state.fixed_values[1] = 1
        return (deductions = 1,)
    end
    return (deductions = 0,)
end

function materialize(ws::Workspace; coefficient_type = Float64)
    n = QUBOTools.dimension(ws.model)
    free = setdiff(collect(1:n), ws._state.fixes)
    if isempty(ws._state.fixes)
        if iszero(PERTURB_NOOP_OFFSET[])
            return (_free = free, _model = ws.model, _ws = ws)
        else
            red_noop = QUBOTools.Model{Int,Float64,Int}(
                Set{Int}(1:n),
                Dict{Int,Float64}(Int(i) => Float64(v) for (i, v) in QUBOTools.linear_terms(ws.model)),
                Dict{Tuple{Int,Int},Float64}(
                    (Int(i), Int(j)) => Float64(v) for ((i, j), v) in QUBOTools.quadratic_terms(ws.model)
                );
                offset = Float64(QUBOTools.offset(ws.model)) + PERTURB_NOOP_OFFSET[],
                domain = QUBOTools.domain(ws.model),
                sense  = QUBOTools.sense(ws.model),
            )
            return (_free = free, _model = red_noop, _ws = ws)
        end
    end
    if isempty(free) && !isempty(ws._state.fixed_values)
        fixed_state = [ws._state.fixed_values[i] for i in 1:n]
        off = Float64(QUBOTools.value(ws.model, fixed_state))
    else
        off = -1.0
    end
    red = QUBOTools.Model{Int,Float64,Int}(
        Set{Int}(1:length(free)),
        Dict{Int,Float64}(i => -1.0 for i in 1:length(free)),
        Dict{Tuple{Int,Int},Float64}();
        offset = off,
        domain = :bool,
        sense  = QUBOTools.sense(ws.model),
    )
    return (_free = free, _model = red, _ws = ws)
end

export_model(mat) = mat._model

function export_certificate(ws::Workspace)
    FORCE_MISSING_CERT[] && return nothing
    FORCE_EMPTY_CERT[] && return (steps = Int[],)
    return isempty(ws._state.fixes) ? nothing : (steps = copy(ws._state.fixes),)
end

function verify_certificate(ws::Workspace, cert)
    VERIFY_DELAY[] > 0 && sleep(VERIFY_DELAY[])
    return (valid = !isnothing(cert) && !isempty(cert.steps) && ws.cert_valid,)
end

function index_map(mat)
    result = zeros(Int, QUBOTools.dimension(mat._ws.model))
    for (k, i) in enumerate(mat._free)
        result[i] = k
    end
    return result
end

function schedule_budgeted!(ws::Workspace; time_limit, allow_weak = false, kwargs...)
    RECORDED_BUDGET[] = time_limit
    RECORDED_OPTIONS[] = (; kwargs...)
    SCHEDULE_DELAY[] > 0 && sleep(SCHEDULE_DELAY[])
    n = QUBOTools.dimension(ws.model)
    r = schedule_reductions!(ws; enable_blocks = true, allow_weak_dominance = allow_weak)
    apply_submodular_cut!(ws; allow_weak)
    pr = n == 2 && isempty(ws._state.fixes) ? probe_variables!(ws; order = :coercive) : (deductions = 0,)
    return (stop_reason = length(ws._state.fixes) == n ? :solved : :fixpoint,
            passes = 1, elapsed_s = SCHEDULE_DELAY[], initial_variables = n,
            residual_variables = n - length(ws._state.fixes),
            families = [(family = :cheap, calls = 1, time_s = 0.0,
                         freed = r.dominance_deductions, stop_reason = :fixpoint),
                        (family = :probing, calls = 1, time_s = 0.0,
                         freed = pr.deductions, stop_reason = :fixpoint)])
end

function reconstruct(mat, reduced_state::AbstractVector{<:Integer})
    ws = mat._ws
    n = QUBOTools.dimension(ws.model)
    if isempty(ws._state.fixes)
        return (state = collect(Int, reduced_state),)
    end
    if isempty(mat._free) && length(ws._state.fixed_values) == n
        return (state = [ws._state.fixed_values[i] for i in 1:n],)
    end
    return (state = vcat([1], collect(Int, reduced_state)),)
end

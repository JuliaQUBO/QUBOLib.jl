                        QUBOLib.database(index),
                        "SELECT instance, name, source_name, problem_class, formulation, metadata FROM Instances WHERE collection = 'mqlib' ORDER BY instance;",
                    ) |> QUBOLib.DataFrame
                    @test size(inst_df, 1) == 3

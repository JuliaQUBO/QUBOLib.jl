function _wrap_fallback_res(res::NamedTuple)
    if RETURN_STRUCT_RESULT[]
        return _FallbackStructResult(
            res.model,
            collect(Int, res.surviving_variables),
            res.trace,
            INJECT_CERTIFIED_TRUE[],
            Dict{String,Any}("dominance" => 1),
        )
    end
